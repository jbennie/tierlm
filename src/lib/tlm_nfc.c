static int src_idx(const uint32_t *src, unsigned n, uint32_t cp, unsigned *idx) {
    unsigned a = 0, b = n;
    while (b - a > 1) {
        unsigned m = a + (b - a) / 2;
        if (src[m] <= cp) a = m; else b = m;
    }
    if (a < n && src[a] == cp) { *idx = a; return 1; }
    return 0;
}

static int ccc(uint32_t cp) {
    unsigned idx;
    return src_idx(ccc_a, ccc_n, cp, &idx) ? (int)ccc_b[idx] : 0;
}

/* Append the CDMA of cp to dst[0..cap); *len is the running count.
 * Returns 0, or -1 if it does not fit. The mapping recurses: a 1-part
 * decomposition expands its part; a 2-part decomposition expands the
 * first part and appends the second (which is always unbreakable);
 * hangul syllables map to jamo. */
static int cdma(uint32_t cp, uint32_t *dst, int *len, int cap) {
    unsigned idx;
    if (src_idx(dec_src, dec_n, cp, &idx)) {
        int k = (int)dec_len[idx];
        if (k == 1)
            return cdma(dec_cps[dec_off[idx]], dst, len, cap);
        if (k == 2) {
            if (cdma(dec_cps[dec_off[idx]], dst, len, cap) < 0) return -1;
            if (*len + 1 > cap) return -1;
            dst[(*len)++] = dec_cps[dec_off[idx] + 1];
            return 0;
        }
        if (*len + k > cap) return -1;
        for (int j = 0; j < k; j++) dst[(*len)++] = dec_cps[dec_off[idx] + j];
        return 0;
    }
    if (cp >= 0xAC00 && cp <= 0xD7A3) {
        int S = (int)(cp - 0xAC00);
        int T = S % 28;
        if (*len + 3 > cap) return -1;
        dst[(*len)++] = (uint32_t)(0x1100 + S / 588);
        dst[(*len)++] = (uint32_t)(0x1161 + (S % 588) / 28);
        if (T) dst[(*len)++] = (uint32_t)(0x11A7 + T);
        return 0;
    }
    if (*len + 1 > cap) return -1;
    dst[(*len)++] = cp;
    return 0;
}

/* Binary search of the composition table by (a, b); returns the row or
 * -1. */
static int comp_lookup(uint32_t a, uint32_t b) {
    unsigned lo = 0, hi = comp_n;
    while (hi - lo > 1) {
        unsigned m = lo + (hi - lo) / 2;
        if (comp_a[m] < a || (comp_a[m] == a && comp_b[m] <= b)) lo = m;
        else hi = m;
    }
    return (lo < comp_n && comp_a[lo] == a && comp_b[lo] == b) ? (int)lo : -1;
}

/* Fill dst (capacity cap codepoints; 3 * n always suffices) with the NFC
 * form of cps[0..n). Returns the output length in codepoints, or -1 if
 * it does not fit. cps and dst must not overlap. */
int tlm_nfc_normalize(const uint32_t *cps, int n, uint32_t *dst, int cap) {
    int out_n = 0;
    /* 1: expand every codepoint with the canonical decomposition
     * mapping (NFD decomposition half) */
    for (int i = 0; i < n; i++)
        if (cdma(cps[i], dst, &out_n, cap) < 0) return -1;
    /* 2: canonical reordering: stable sort of each maximal run of
     * combining marks by ascending ccc (insertion sort; runs are short) */
    for (int i = 0; i < out_n; i++) {
        if (ccc(dst[i]) == 0) continue;
        int j = i;
        while (j < out_n && ccc(dst[j]) > 0) j++;
        for (int a = i + 1; a < j; a++) {
            uint32_t m = dst[a];
            int b = a;
            while (b > i && ccc(dst[b - 1]) > ccc(m)) {
                dst[b] = dst[b - 1];
                b--;
            }
            dst[b] = m;
        }
        i = j - 1;
    }
    /* 3: composition scan (UAX #15 procedure): for a mark at i, the
     * base it may compose with is found by walking left past marks of
     * strictly smaller class; a starter at i composes with its
     * immediate left neighbor. After any composition, re-check the pair
     * to the left of the result. */
    {
        int i = 1;
        while (i < out_n) {
            if (ccc(dst[i]) > 0) {
                int j = i - 1;
                while (j >= 0 && ccc(dst[j]) > 0 && ccc(dst[j]) < ccc(dst[i])) j--;
                if (j >= 0) {
                    int row = comp_lookup(dst[j], dst[i]);
                    if (row >= 0) {
                        dst[j] = comp_c[row];
                        memmove(dst + i, dst + i + 1, (size_t)(out_n - i - 1) * sizeof(uint32_t));
                        out_n--;
                        i = j > 0 ? j : 1;
                        continue;
                    }
                }
            } else {
                int row = comp_lookup(dst[i - 1], dst[i]);
                if (row >= 0) {
                    dst[i - 1] = comp_c[row];
                    memmove(dst + i, dst + i + 1, (size_t)(out_n - i - 1) * sizeof(uint32_t));
                    out_n--;
                    i = i > 1 ? i - 1 : 1;
                    continue;
                }
            }
            i++;
        }
    }
    /* 4: Hangul, left to right: (L, V) -> LV, (L, V, T) -> LVT, (LV
     * with no final, T) -> LVT. No exclusions apply (the 7 excluded
     * jamos are never composition results). */
    int i = 0;
    while (i + 1 < out_n) {
        uint32_t x = dst[i], y = dst[i + 1];
        if (x >= 0x1100 && x <= 0x1112 && y >= 0x1161 && y <= 0x1175) {
            int t = (i + 2 < out_n && dst[i + 2] >= 0x11A8 && dst[i + 2] <= 0x11C2);
            int S = (int)(x - 0x1100) * 588 + (int)(y - 0x1161) * 28 + (t ? (int)(dst[i + 2] - 0x11A7) : 0);
            dst[i] = 0xAC00 + (uint32_t)S;
            memmove(dst + i + 1, dst + i + 1 + t, (size_t)(out_n - i - 1 - t) * sizeof(uint32_t));
            out_n -= 1 + (t ? 1 : 0);
            i++;
            continue;
        }
        if (x >= 0xAC00 && x <= 0xD7A3 && (int)(x - 0xAC00) % 28 == 0 &&
            y >= 0x11A8 && y <= 0x11C2) {
            dst[i] = 0xAC00 + (uint32_t)((int)(x - 0xAC00) + (int)(y - 0x11A7));
            memmove(dst + i + 1, dst + i + 2, (size_t)(out_n - i - 2) * sizeof(uint32_t));
            out_n--;
            i++;
            continue;
        }
        i++;
    }
    return out_n;
}
